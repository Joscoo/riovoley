const fs=require('node:fs');
const path=require('node:path');
const cp=require('node:child_process');
const crypto=require('node:crypto');
const root=path.resolve(__dirname,'../../..'),runtime=path.join(root,'.e2e-local');
const stamp=new Date().toISOString().replace(/[-:]/g,'').replace('T','-').slice(0,15);
const commit=cp.execFileSync('git',['rev-parse','HEAD'],{cwd:root,encoding:'utf8'}).trim();
const status=cp.execFileSync('git',['status','--short'],{cwd:root,encoding:'utf8'});
const base=path.join(root,'docs/tesis/evidencias/verificacion-tecnica',stamp+'-e2e-final-'+commit.slice(0,7));
const pointer=path.join(runtime,'evidence-dir.txt');
fs.copyFileSync(pointer,path.join(runtime,'evidence-before-e2e-final-'+stamp+'.txt'),fs.constants.COPYFILE_EXCL);
for(const dir of ['unitarias','integracion','e2e','compilacion-web','android','seguridad'])fs.mkdirSync(path.join(base,dir),{recursive:true});
fs.writeFileSync(pointer,base+'\n');
const h=require('../../e2e/local/harness.cjs');
h.write('CONTEXTO.json',{commit,createdAt:new Date().toISOString(),scope:'Repetición autorizada de 249 instancias Playwright sobre el último commit, con backend local descartable. Sin producción, despliegues ni cambios de esquema.',previousEvidencePreserved:true,productionChanged:false});
h.write('estado-inicial.txt',status);
const files=cp.execFileSync('git',['ls-files','-z'],{cwd:root}).toString().split('\0').filter(f=>f&&/^(src\/|tests\/|scripts\/e2e\/|playwright|package(?:-lock)?\.json)/.test(f));
h.write('fuentes-evaluadas.json',files.map(file=>({file,sha256:crypto.createHash('sha256').update(fs.readFileSync(path.join(root,file))).digest('hex')})));
console.log(path.relative(root,base));
