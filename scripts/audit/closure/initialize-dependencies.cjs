const fs=require('node:fs');
const path=require('node:path');
const cp=require('node:child_process');
const crypto=require('node:crypto');
const os=require('node:os');
const root=path.resolve(__dirname,'../../..'),runtime=path.join(root,'.e2e-local');
const commit=cp.execFileSync('git',['rev-parse','HEAD'],{cwd:root,encoding:'utf8'}).trim();
const stamp=new Date().toISOString().replace(/[-:]/g,'').replace('T','-').slice(0,15);
const evidence=path.join(root,'docs/tesis/evidencias/verificacion-tecnica',stamp+'-dependencias-'+commit.slice(0,7));
const pointer=path.join(runtime,'evidence-dir.txt');
fs.copyFileSync(pointer,path.join(runtime,'evidence-before-dependencies-'+stamp+'.txt'),fs.constants.COPYFILE_EXCL);
for(const dir of ['unitarias','integracion','e2e','compilacion-web','android','seguridad'])fs.mkdirSync(path.join(evidence,dir),{recursive:true});
fs.writeFileSync(pointer,evidence+'\n');
const h=require('../../e2e/local/harness.cjs');
h.write('CONTEXTO.json',{createdAt:new Date().toISOString(),commit,scope:'Continuación autorizada: diagnóstico y correcciones compatibles de dependencias, sin cambios institucionales, despliegues, migración de framework ni actualizaciones forzadas.',os:os.type(),release:os.release(),architecture:os.arch(),node:process.version});
h.write('estado-inicial.txt',cp.execFileSync('git',['status','--short'],{cwd:root,encoding:'utf8'}));
const files=cp.execFileSync('git',['ls-files','-z'],{cwd:root}).toString().split('\0').filter(f=>f&&/^(src\/|tests\/|scripts\/|playwright|capacitor|android\/[^/]+\.(?:gradle|json)|(?:functions\/|riovoley\/)?package(?:-lock)?\.json)/.test(f));
h.write('fuentes-iniciales.json',files.map(file=>({file,sha256:crypto.createHash('sha256').update(fs.readFileSync(path.join(root,file))).digest('hex')})));
console.log(path.relative(root,evidence));
